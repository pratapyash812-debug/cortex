"""Real archive integrity, ownership, cancellation and nonblocking capture."""
import hashlib,json,sys,tempfile,threading,time,unittest,zipfile
from pathlib import Path
from unittest.mock import patch
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
import server,auto_backup,file_snapshot

class BackupTests(unittest.TestCase):
    def setUp(self):
        self.temp=tempfile.TemporaryDirectory();self.root=Path(self.temp.name);self.v=server.Vault(self.root/'vault')
        self.v.create('Maths','Lesson','Saved equation x²')
        self.service=auto_backup.BackupService(self.v,self.root/'backups',retention=2)
    def tearDown(self):self.service.stop();self.temp.cleanup()

    def test_verified_full_archive_preserves_sources_history_ink_but_not_caches(self):
        originals={'Sources/Book.pdf':b'PDF original bytes','.cortex/history/Maths/Lesson.md/old.md':b'Previous note','.cortex/canvas/Graph.canvas.draw.json':b'{"strokes":[]}', '.cortex/notebooks.json':b'{}'}
        omitted={'.cortex/search/index.sqlite3':b'cache','.cortex/writer.lock':b'', 'Sources/~$Book.docx':b'office owner','draft.tmp':b'partial'}
        for rel,data in {**originals,**omitted}.items():
            p=self.v.root/rel;p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(data)
        before=(self.v.root/'Maths/Lesson.md').read_bytes();item=self.service.run_once(manual=True)
        with zipfile.ZipFile(item['path']) as archive:
            self.assertEqual(archive.read('Maths/Lesson.md'),before)
            for rel,data in originals.items():self.assertEqual(archive.read(rel),data)
            self.assertFalse(set(omitted)&set(archive.namelist()))
        self.assertEqual(hashlib.sha256(Path(item['path']).read_bytes()).hexdigest(),item['sha256'])
        self.assertEqual((self.v.root/'Maths/Lesson.md').read_bytes(),before)
        self.assertTrue(self.service.status()['localOnly'])

    def test_retention_removes_only_owned_verified_archives(self):
        self.service.run_once(manual=True)
        unrelated=self.service.destination/'cortex-auto-20200101-000000-aaaaaaaaaaaa.zip';unrelated.write_bytes(b'user file, never generated by Cortex')
        first=self.service.status()['lastBackup']['path']
        for content in ('Second version','Third version'):
            n=self.v.info(self.v.resolve('Maths/Lesson.md'),True);self.v.save(n['path'],content,None,n['revision']);self.service.run_once(manual=True)
        self.assertFalse(Path(first).exists());self.assertTrue(unrelated.is_file());self.assertEqual(self.service.status()['archives'],2)

    def test_concurrent_edit_rejects_capture_and_keeps_previous_backup(self):
        old=self.service.run_once(manual=True);copy=file_snapshot.copy_stable;changed=False
        def mutate(*args,**kwargs):
            nonlocal changed
            value=copy(*args,**kwargs)
            if not changed:
                changed=True;n=self.v.info(self.v.resolve('Maths/Lesson.md'),True);self.v.save(n['path'],'Foreground edit',None,n['revision'])
            return value
        with patch.object(file_snapshot,'copy_stable',mutate):
            with self.assertRaises(file_snapshot.InputChanged):self.service.run_once(manual=True)
        self.assertTrue(Path(old['path']).is_file());self.assertEqual(self.service.status()['lastBackup'],old)

    def test_compression_never_holds_the_notebook_writer(self):
        opened=zipfile.ZipFile.open;obtained=[]
        def archive_open(z,name,mode='r',*args,**kwargs):
            if mode=='w':
                def writer():
                    with self.v._note_save_lock.hold(timeout=.2):obtained.append(True)
                thread=threading.Thread(target=writer);thread.start();thread.join(1)
                self.assertFalse(thread.is_alive())
            return opened(z,name,mode,*args,**kwargs)
        with patch.object(zipfile.ZipFile,'open',archive_open):self.service.run_once(manual=True)
        self.assertTrue(obtained)

    def test_stop_cancels_owned_worker_without_publishing_partial_backup(self):
        entered=threading.Event()
        def paused_copy(*args,**kwargs):
            entered.set()
            while not args[3]():time.sleep(.005)
            raise file_snapshot.WorkCancelled()
        with patch.object(file_snapshot,'copy_stable',paused_copy):
            self.service.request_run();self.assertTrue(entered.wait(2));self.service.stop()
        self.assertFalse(self.service._thread.is_alive());self.assertEqual(self.service.status()['archives'],0)

    def test_unchanged_idle_scan_is_deduplicated_and_destination_cannot_be_inside_vault(self):
        first=self.service.run_once(manual=True)
        self.assertEqual(self.service.run_once(),first);self.assertEqual(self.service.status()['archives'],1)
        with self.assertRaises(ValueError):auto_backup.BackupService(self.v,self.v.root/'Backups')

    def test_malformed_metadata_never_breaks_status_or_authorises_deletion(self):
        self.service.destination.mkdir()
        p=self.service.destination/'cortex-auto-20200101-000000-aaaaaaaaaaaa.zip.json'
        p.write_text(json.dumps({'format':auto_backup.FORMAT,'vaultId':self.service.identifier,'archive':'../user.zip'}))
        self.assertEqual(self.service.status()['archives'],0);self.assertTrue(p.is_file())

if __name__=='__main__':unittest.main()
